CREATE VIEW v_funil_comercial AS
SELECT
    count(*) FILTER (WHERE status = 'prospecto')        AS prospectos,
    count(*) FILTER (WHERE status = 'contatado')        AS contatados,
    count(*) FILTER (WHERE status = 'reuniao_marcada')  AS reunioes,
    count(*) FILTER (WHERE status = 'proposta')         AS propostas,
    count(*) FILTER (WHERE status = 'negociacao')       AS negociacoes,
    count(*) FILTER (WHERE status = 'fechado')          AS fechados,
    count(*) FILTER (WHERE status = 'perdido')          AS perdidos,
    COALESCE(sum(valor_estimado) FILTER (WHERE status IN ('proposta', 'negociacao')), 0) AS pipeline_valor
FROM clientes;

CREATE VIEW v_propostas_detalhe AS
SELECT p.id, p.numero, p.titulo, p.valor_total, p.status, p.data_envio, p.validade_dias,
       c.nome_fantasia, c.razao_social, c.uf, a.nome AS responsavel
FROM propostas p
JOIN clientes c ON c.id = p.cliente_id
LEFT JOIN agentes a ON a.id = p.responsavel_id;

CREATE VIEW v_demandas_abertas AS
SELECT d.id, d.codigo, d.titulo, d.prioridade, d.prazo, d.progresso,
       f.nome AS fase, f.cor AS cor_fase,
       a.nome AS responsavel, ad.nome AS area, pr.codigo AS projeto
FROM demandas d
JOIN fases f ON f.codigo = d.fase::text
LEFT JOIN agentes a             ON a.id = d.responsavel_id
LEFT JOIN areas_departamento ad ON ad.id = d.area_id
LEFT JOIN projetos pr           ON pr.id = d.projeto_id
WHERE d.fase <> 'concluida'
ORDER BY d.prazo NULLS LAST, d.prioridade DESC, d.id;

CREATE VIEW v_telemetria_ultima AS
SELECT DISTINCT ON (se.id)
       s.codigo AS site, s.nome AS site_nome, se.codigo AS sensor, se.grandeza, se.unidade,
       l.instante, l.valor, l.qualidade
FROM sensores se
JOIN sites s ON s.id = se.site_id
LEFT JOIN leituras l ON l.sensor_id = se.id
ORDER BY se.id, l.instante DESC;

CREATE VIEW v_ndvi_serie AS
SELECT s.codigo AS site, si.indice, si.data, si.valor, si.origem, si.fonte
FROM series_indices si
JOIN sites s ON s.id = si.site_id
ORDER BY s.codigo, si.indice, si.data;

CREATE VIEW v_fluxo_caixa_mensal AS
SELECT date_trunc('month', data)::date AS mes,
       tipo,
       sum(valor) FILTER (WHERE status = 'realizado') AS realizado,
       sum(valor) FILTER (WHERE status = 'previsto')  AS previsto
FROM lancamentos
WHERE status <> 'cancelado'
GROUP BY 1, 2
ORDER BY 1;

CREATE VIEW v_resumo_financeiro AS
SELECT
    (SELECT COALESCE(sum(valor),0) FROM lancamentos WHERE tipo = 'receita' AND status = 'realizado') AS receita_realizada,
    (SELECT COALESCE(sum(valor),0) FROM lancamentos WHERE tipo = 'despesa' AND status = 'realizado') AS despesa_realizada,
    (SELECT COALESCE(sum(valor),0) FROM lancamentos WHERE tipo = 'receita' AND status = 'previsto')  AS receita_prevista,
    (SELECT COALESCE(sum(valor),0) FROM lancamentos WHERE tipo = 'despesa' AND status = 'previsto')  AS despesa_prevista,
    (SELECT COALESCE(sum(valor),0) FROM cobrancas WHERE status IN ('aberta', 'atrasada'))           AS a_receber;

CREATE VIEW v_margem_proposta AS
SELECT p.id, p.numero, p.titulo, p.valor_total,
       COALESCE(sum(i.valor_unitario * i.quantidade), 0) AS total_itens,
       p.valor_total - COALESCE(sum(i.valor_unitario * i.quantidade), 0) AS diferenca
FROM propostas p
LEFT JOIN itens_proposta i ON i.proposta_id = p.id
GROUP BY p.id, p.numero, p.titulo, p.valor_total;

CREATE VIEW v_painel_executivo AS
SELECT
    (SELECT count(*) FROM agentes WHERE ativo)                                                     AS agentes_ativos,
    (SELECT count(*) FROM demandas WHERE fase <> 'concluida')                                       AS demandas_abertas,
    (SELECT count(*) FROM clientes WHERE status IN ('proposta', 'negociacao'))                      AS oportunidades,
    (SELECT COALESCE(sum(valor_estimado),0) FROM clientes WHERE status IN ('proposta', 'negociacao')) AS pipeline_valor,
    (SELECT COALESCE(sum(valor),0) FROM cobrancas
        WHERE status = 'paga' AND date_trunc('month', data_pagamento) = date_trunc('month', CURRENT_DATE)) AS receita_mes,
    (SELECT count(*) FROM alertas WHERE lida = false)                                                AS alertas_nao_lidas;

COMMIT;
