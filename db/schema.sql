-- 1) mantém atualizado_em
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.atualizado_em := now();
    RETURN NEW;
END; $$ LANGUAGE plpgsql;

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['clientes', 'propostas', 'contratos', 'projetos',
                             'demandas', 'sites', 'lancamentos', 'vendas_kits', 'configuracoes']
    LOOP
        EXECUTE format('CREATE TRIGGER trg_%s_updated BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()', t, t);
    END LOOP;
END $$;

-- 2) demandas: concluída ⇒ progresso 100; loga histórico; recalcula progresso do projeto
CREATE OR REPLACE FUNCTION fn_demanda_trigger() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND (NEW.fase IS DISTINCT FROM OLD.fase
                          OR NEW.progresso IS DISTINCT FROM OLD.progresso) THEN
        IF NEW.fase = 'concluida' THEN NEW.progresso := 100; END IF;
        INSERT INTO historico_demandas (demanda_id, fase_anterior, fase_nova,
                                        progresso_anterior, progresso_novo, agente_autor_id)
        VALUES (NEW.id, OLD.fase, NEW.fase, OLD.progresso, NEW.progresso, NEW.responsavel_id);
        IF NEW.projeto_id IS NOT NULL THEN
            UPDATE projetos SET progresso = COALESCE((SELECT ROUND(AVG(progresso))
                                                      FROM demandas WHERE projeto_id = NEW.projeto_id), 0)
            WHERE id = NEW.projeto_id AND status NOT IN ('concluido', 'cancelado');
        END IF;
    ELSIF TG_OP = 'INSERT' THEN
        IF NEW.fase = 'concluida' THEN NEW.progresso := 100; END IF;
        IF NEW.projeto_id IS NOT NULL THEN
            UPDATE projetos SET progresso = COALESCE((SELECT ROUND(AVG(progresso))
                                                      FROM demandas WHERE projeto_id = NEW.projeto_id), 0)
            WHERE id = NEW.projeto_id AND status NOT IN ('concluido', 'cancelado');
        END IF;
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_demanda
    BEFORE INSERT OR UPDATE ON demandas
    FOR EACH ROW EXECUTE FUNCTION fn_demanda_trigger();

-- 3) auditoria genérica (clientes, propostas, contratos)
CREATE OR REPLACE FUNCTION fn_auditar() RETURNS trigger AS $$
DECLARE
    antes  jsonb;
    depois jsonb;
BEGIN
    antes  := CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) ELSE NULL END;
    depois := CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN to_jsonb(NEW) ELSE NULL END;
    INSERT INTO auditoria (tabela, registro_id, acao, dados_antes, dados_depois)
    VALUES (TG_TABLE_NAME, COALESCE(NEW.id, OLD.id), TG_OP, antes, depois);
    RETURN COALESCE(NEW, OLD);
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_clientes_audit  AFTER INSERT OR UPDATE OR DELETE ON clientes  FOR EACH ROW EXECUTE FUNCTION fn_auditar();
CREATE TRIGGER trg_propostas_audit AFTER INSERT OR UPDATE OR DELETE ON propostas FOR EACH ROW EXECUTE FUNCTION fn_auditar();
CREATE TRIGGER trg_contratos_audit AFTER INSERT OR UPDATE OR DELETE ON contratos FOR EACH ROW EXECUTE FUNCTION fn_auditar();

